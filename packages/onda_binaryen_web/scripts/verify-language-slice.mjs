import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  compileTrustedMir as compileMir,
  createDefaultImports,
} from "../src/index.js";

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoDir = resolve(packageDir, "../..");
const source = join(packageDir, "test/fixtures/language-slice.onda");
const temporary = mkdtempSync(join(tmpdir(), "onda-binaryen-web-"));
const mirPath = join(temporary, "language-slice.mir.msgpack");

try {
  execFileSync(
    "cargo",
    [
      "run",
      "-q",
      "-p",
      "onda_cli",
      "--",
      "compile",
      source,
      "--emit",
      "mir-messagepack",
      "--output",
      mirPath,
      "--block-size",
      "4",
    ],
    { cwd: repoDir, stdio: "inherit" },
  );

  const artifact = compileMir(readFileSync(mirPath));
  if (!WebAssembly.validate(artifact.wasm)) {
    throw new Error("generated bytes are not valid WebAssembly");
  }
  const event = artifact.metadata.metadata.events[0];
  const controlOutput = artifact.metadata.metadata.control_outputs[0];
  if (
    artifact.metadata.exports.events[0] !== "onda_event_0" ||
    event.payload_size_bytes !== 12 ||
    event.params[1].byte_offset !== 4 ||
    event.params[1].is_array !== true
  ) {
    throw new Error("event ABI metadata does not match the Onda payload layout");
  }

  const { instance } = await WebAssembly.instantiate(
    artifact.wasm,
    createDefaultImports(),
  );
  const { memory, __heap_base, onda_init, onda_process, onda_event_0 } =
    instance.exports;
  let heap = Number(__heap_base.value);
  const allocate = (bytes, alignment = 16) => {
    heap = Math.ceil(heap / alignment) * alignment;
    const pointer = heap;
    heap += bytes;
    return pointer;
  };
  const params = allocate(artifact.metadata.runtime.param_size_bytes);
  const state = allocate(artifact.metadata.runtime.state_size_bytes);
  const payload = allocate(event.payload_size_bytes, 4);
  const outputTable = allocate(4, 4);
  const output = allocate(4 * artifact.metadata.compile.block_size);
  const view = new DataView(memory.buffer);
  view.setFloat32(params, 0.5, true);
  view.setInt32(payload, 3, true);
  view.setFloat32(payload + 4, 2, true);
  view.setFloat32(payload + 8, 4, true);
  view.setUint32(outputTable, output, true);

  onda_init(params, state);
  onda_event_0(payload, params, state, 0, 0, 0, 0);
  onda_process(0, outputTable, 0, 4, 3, params, state, 0, 0, 0, 0);

  const samples = [...new Float32Array(memory.buffer, output, 4)];
  const expected = [10, 13, 16, 19];
  if (!samples.every((sample, index) => sample === expected[index])) {
    throw new Error(`unexpected real-Onda render: ${JSON.stringify(samples)}`);
  }
  const meter = view.getFloat32(
    state + controlOutput.state_byte_offset,
    true,
  );
  if (meter !== 7) {
    throw new Error(`unexpected control output value ${meter}`);
  }

  let WorkletProcessor;
  globalThis.AudioWorkletProcessor = class {
    constructor() {
      this.port = {
        messages: [],
        onmessage: null,
        postMessage: (message) => this.port.messages.push(message),
      };
    }
  };
  globalThis.registerProcessor = (_name, processor) => {
    WorkletProcessor = processor;
  };
  await import(
    new URL(
      "../../../examples/web/onda_wasm_playground/onda-wasm-processor.js",
      import.meta.url,
    )
  );
  const processor = new WorkletProcessor({
    processorOptions: { wasmBytes: artifact.wasm, metadata: artifact.metadata },
  });
  processor.port.onmessage({
    data: {
      type: "event",
      event: "set_phase",
      values: { step: 3, values: new Float32Array([2, 4]) },
    },
  });
  const browserOutput = new Float32Array(4);
  processor.process([], [[browserOutput]]);
  if (!browserOutput.every((sample, index) => sample === expected[index])) {
    throw new Error(
      `unexpected AudioWorklet render: ${JSON.stringify([...browserOutput])}`,
    );
  }
  processor.port.onmessage({ data: { type: "read-control-outputs" } });
  const controlMessage = processor.port.messages.find(
    (message) => message.type === "control-outputs",
  );
  if (controlMessage?.values?.meter !== 7) {
    throw new Error("AudioWorklet did not expose the expected control output");
  }

  const bufferSource = join(packageDir, "test/fixtures/buffer-slice.onda");
  const bufferMirPath = join(temporary, "buffer-slice.mir.msgpack");
  execFileSync(
    "cargo",
    [
      "run",
      "-q",
      "-p",
      "onda_cli",
      "--",
      "compile",
      bufferSource,
      "--emit",
      "mir-messagepack",
      "--output",
      bufferMirPath,
      "--block-size",
      "4",
    ],
    { cwd: repoDir, stdio: "inherit" },
  );
  const bufferArtifact = compileMir(readFileSync(bufferMirPath));
  const bufferMetadata = bufferArtifact.metadata.metadata.buffers;
  if (
    bufferMetadata.length !== 2 ||
    bufferMetadata[0].channels !== "mono" ||
    bufferMetadata[1].channels !== "static" ||
    bufferMetadata[1].static_channels !== 2
  ) {
    throw new Error("buffer ABI metadata does not match the Onda declarations");
  }
  const bufferProcessor = new WorkletProcessor({
    processorOptions: {
      wasmBytes: bufferArtifact.wasm,
      metadata: bufferArtifact.metadata,
      buffers: {
        table: {
          data: new Float32Array([1, 2, 3, 4]),
          frames: 4,
          channels: 1,
          sampleRate: 10,
        },
        bus: {
          data: new Float32Array([10, 20, 11, 21, 12, 22, 13, 23]),
          frames: 4,
          channels: 2,
          sampleRate: 10,
        },
      },
    },
  });
  const bufferOutput = new Float32Array(4);
  bufferProcessor.process([], [[bufferOutput]]);
  const expectedBufferOutput = [38, 40, 42, 44];
  if (
    !bufferOutput.every(
      (sample, index) => sample === expectedBufferOutput[index],
    )
  ) {
    throw new Error(
      `unexpected external-buffer render: ${JSON.stringify([...bufferOutput])}`,
    );
  }
  const tableAfter = bufferProcessor.readBuffer("table").data;
  const busAfter = bufferProcessor.readBuffer("bus").data;
  if (
    JSON.stringify(tableAfter) !== JSON.stringify([2, 3, 4, 5]) ||
    JSON.stringify(busAfter) !==
      JSON.stringify([22, 20, 23, 21, 24, 22, 25, 23])
  ) {
    throw new Error("external-buffer writes did not preserve interleaved layout");
  }

  const sliceSource = join(packageDir, "test/fixtures/slice-semantics.onda");
  const sliceMirPath = join(temporary, "slice-semantics.mir.msgpack");
  execFileSync(
    "cargo",
    [
      "run",
      "-q",
      "-p",
      "onda_cli",
      "--",
      "compile",
      sliceSource,
      "--emit",
      "mir-messagepack",
      "--output",
      sliceMirPath,
      "--block-size",
      "4",
    ],
    { cwd: repoDir, stdio: "inherit" },
  );
  const sliceArtifact = compileMir(readFileSync(sliceMirPath));
  const sliceProcessor = new WorkletProcessor({
    processorOptions: {
      wasmBytes: sliceArtifact.wasm,
      metadata: sliceArtifact.metadata,
    },
  });
  const sliceEvent = sliceArtifact.metadata.metadata.events[0];
  if (
    sliceEvent?.has_dynamic_payload !== true ||
    sliceEvent.params[1]?.is_slice !== true ||
    sliceEvent.params[1]?.type !== "f32[]" ||
    sliceEvent.params[2]?.byte_offset !== null
  ) {
    throw new Error("slice event metadata does not describe its dynamic payload");
  }
  sliceProcessor.port.onmessage({
    data: {
      type: "event",
      event: "seed",
      values: {
        scale: 2,
        values: new Float32Array([4, 8]),
        add: 1,
      },
    },
  });
  const sliceOutput = new Float32Array(4);
  sliceProcessor.process([], [[sliceOutput]]);
  const expectedSliceOutput = [31, 32, 33, 34];
  if (
    !sliceOutput.every(
      (sample, index) => sample === expectedSliceOutput[index],
    )
  ) {
    throw new Error(
      `unexpected primitive-slice render: ${JSON.stringify([...sliceOutput])}`,
    );
  }

  process.stdout.write(
    `Verified Onda -> MIR -> Binaryen -> Wasm -> AudioWorklet: tuples/events/control ${artifact.wasm.byteLength} bytes; buffers ${bufferArtifact.wasm.byteLength} bytes; slices ${sliceArtifact.wasm.byteLength} bytes; samples ${samples.join(", ")}; buffer samples ${[...bufferOutput].join(", ")}; slice samples ${[...sliceOutput].join(", ")}\n`,
  );
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
