import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const kernelRoot = resolve(packageRoot, "math-kernel");
const output = resolve(packageRoot, "src/math-kernel.generated.js");

const build = spawnSync(
  "cargo",
  ["build", "--locked", "--target", "wasm32-unknown-unknown", "--release"],
  { cwd: kernelRoot, encoding: "utf8", stdio: "pipe" },
);
if (build.status !== 0) {
  process.stderr.write(build.stderr);
  process.exit(build.status ?? 1);
}

const wasmPath = resolve(
  kernelRoot,
  "target/wasm32-unknown-unknown/release/onda_wasm_math_kernel.wasm",
);
const wasm = readFileSync(wasmPath);
const module = new WebAssembly.Module(wasm);
const imports = WebAssembly.Module.imports(module);
if (imports.length !== 0) {
  throw new Error(`math kernel unexpectedly has ${imports.length} imports`);
}

const expectedExports = [
  "memory",
  ...["sin", "cos", "tan", "tanh", "atan", "atan2", "exp", "log", "pow", "remainder", "fma"]
    .flatMap((intrinsic) => [
      `onda_math_${intrinsic}_f32`,
      `onda_math_${intrinsic}_f64`,
    ]),
].sort();
const actualExports = WebAssembly.Module.exports(module)
  .map(({ name }) => name)
  .sort();
if (JSON.stringify(actualExports) !== JSON.stringify(expectedExports)) {
  throw new Error(
    `math kernel export mismatch:\nexpected ${expectedExports.join(", ")}\nactual ${actualExports.join(", ")}`,
  );
}

const hash = createHash("sha256").update(wasm).digest("hex");
const generated = `// Generated by scripts/build-math-kernel.mjs; do not edit.\n`
  + `// libm 0.2.16, SHA-256 ${hash}\n`
  + `const BASE64 = "${wasm.toString("base64")}";\n\n`
  + `function decodeBase64(value) {\n`
  + `  if (typeof Buffer !== "undefined") {\n`
  + `    return Uint8Array.from(Buffer.from(value, "base64"));\n`
  + `  }\n`
  + `  const binary = atob(value);\n`
  + `  const bytes = new Uint8Array(binary.length);\n`
  + `  for (let index = 0; index < binary.length; index += 1) {\n`
  + `    bytes[index] = binary.charCodeAt(index);\n`
  + `  }\n`
  + `  return bytes;\n`
  + `}\n\n`
  + `export const ONDA_MATH_KERNEL_WASM = decodeBase64(BASE64);\n`
  + `export const ONDA_MATH_KERNEL_SHA256 = "${hash}";\n`;
writeFileSync(output, generated);
process.stdout.write(`wrote ${output} (${wasm.length} bytes, ${hash})\n`);
